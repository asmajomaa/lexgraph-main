"""Reproduce the three-document BM25 worked example quoted in section 3.

The example is deliberately tiny and hand-checkable: three short documents, a
three-term query, every intermediate value printed by the engine's own
``BM25.explain``.  Nothing here is typed by hand -- the table written to
``report/tables/table_6_bm25_worked_example.md`` is generated from the code, so
the report and the implementation cannot drift apart.

Usage::

    python -m report.bm25_worked_example
"""

from __future__ import annotations

import math
import os
from typing import List

from config import BM25_B, BM25_K1, TABLES_DIR
from core.bm25 import BM25
from core.inverted_index import InvertedIndex
from core.tokenizer import Tokenizer
from data.documents import Document

#: The three toy documents.  Every one of them is short enough that a reader
#: can recount the term frequencies on paper.
TEXTS = [
    "The goalkeeper made a spectacular save during the hockey playoffs.",
    "Hockey playoffs demand a goalkeeper who can save every shot.",
    "The tennis final drew a large crowd to the stadium.",
]

#: The query: three terms, all present in documents 1 and 2, none in 3.
QUERY = "hockey playoffs goalkeeper"


def build_index() -> InvertedIndex:
    """Index the three toy documents.

    Returns:
        A three-document :class:`InvertedIndex`.

    Complexity:
        Time O(total tokens); space O(total tokens).
    """
    documents = [
        Document(doc_id=index, external_id=f"d{index + 1}", text=text, title=f"doc{index + 1}")
        for index, text in enumerate(TEXTS)
    ]
    return InvertedIndex.build(documents, Tokenizer(), name="worked-example")


def render() -> str:
    """Build the markdown table for the report.

    Returns:
        Markdown source.

    Complexity:
        Time O(sum of postings); space O(number of query terms).
    """
    index = build_index()
    scorer = BM25(index)
    terms, idf_by_term = scorer._prepare_query(QUERY)
    lines: List[str] = [
        "# BM25 worked example (generated by `report/bm25_worked_example.py`)",
        "",
        f"Query: `{QUERY}` -> tokenised to `{terms}`.",
        "",
        f"Corpus: N = {index.N}, avgdl = {index.average_document_length:.4f}, "
        f"k1 = {BM25_K1}, b = {BM25_B}.",
        "",
        "| doc | text | tokens (dl) |",
        "|---|---|---|",
    ]
    for doc_id, text in enumerate(TEXTS):
        tokens = index.tokenizer.tokenize(text)
        lines.append(f"| d{doc_id + 1} | {text} | {len(tokens)} ({', '.join(tokens)}) |")

    lines += ["", "## Document frequencies and idf", ""]
    lines.append("| term | df | idf = ln(1 + (N - df + 0.5)/(df + 0.5)) |")
    lines.append("|---|---|---|")
    for term in terms:
        df = index.document_frequency(term)
        raw = (index.N - df + 0.5) / (df + 0.5)
        lines.append(f"| {term} | {df} | ln(1 + {raw:.4f}) = {idf_by_term[term]:.6f} |")

    lines += ["", "## Per-term contributions", ""]
    lines.append(
        "| doc | term | tf | dl | contribution = idf * tf(k1+1) / "
        "(tf + k1(1 - b + b*dl/avgdl)) |"
    )
    lines.append("|---|---|---|---|---|")
    totals = []
    for doc_id in range(index.N):
        rows = scorer.explain(QUERY, doc_id)
        dl = index.doc_lengths[doc_id]
        total = 0.0
        for term, tf, idf, contribution in rows:
            total += contribution
            lines.append(f"| d{doc_id + 1} | {term} | {tf} | {dl} | {contribution:.6f} |")
        totals.append(total)

    lines += ["", "## Final ranking", ""]
    lines.append("| rank | doc | BM25 score |")
    lines.append("|---|---|---|")
    for rank, (score, doc_id) in enumerate(scorer.search(QUERY, k=index.N), start=1):
        lines.append(f"| {rank} | d{doc_id + 1} | {score:.6f} |")

    lines += [
        "",
        "## Hand check of one row",
        "",
        "Document 1, term `hockey`: tf = 1, dl = 6, avgdl = "
        f"{index.average_document_length:.4f}, idf = {idf_by_term['hockey']:.6f}.",
        "",
        "```text",
        "tf * (k1 + 1) = 1 * 2.5 = 2.5",
        f"denominator  = 1 + 1.5 * (1 - 0.75 + 0.75 * 6 / {index.average_document_length:.4f})",
        f"             = {1 + 1.5 * (1 - 0.75 + 0.75 * 6 / index.average_document_length):.6f}",
        f"contribution = {idf_by_term['hockey']:.6f} * 2.5 / "
        f"{1 + 1.5 * (1 - 0.75 + 0.75 * 6 / index.average_document_length):.6f}",
        f"             = {idf_by_term['hockey'] * 2.5 / (1 + 1.5 * (1 - 0.75 + 0.75 * 6 / index.average_document_length)):.6f}",
        "```",
        "",
        f"Summing the three terms for d1 gives {totals[0]:.6f}; d2 is slightly "
        f"lower ({totals[1]:.6f}) because it is one token longer and the same "
        f"three terms therefore carry a larger length penalty. d3 scores "
        f"{totals[2]:.6f} because it contains none of the query terms.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    """Write the worked-example table.

    Returns:
        Exit code.

    Complexity:
        Time O(total tokens); space O(total tokens).
    """
    path = os.path.join(str(TABLES_DIR), "table_6_bm25_worked_example.md")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(render())
    print(f"[worked-example] wrote {path}")
    index = build_index()
    scorer = BM25(index)
    print(scorer.explain_text(QUERY, 0))
    print(scorer.explain_text(QUERY, 1))
    _ = math  # keep the import meaningful if the file is edited later
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
